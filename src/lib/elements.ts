export function iconUrl(item: CatalogItem | undefined): string | null {
  if (!item || !/^\d+$/.test(item.id)) return null;
  const weapon = item.kind !== 'character';
  if (item.game === 'hkrpg') return `${ENKA}/ui/hsr/SpriteOutput/${weapon ? 'LightConeMaxFigures' : 'AvatarRoundIcon/Avatar'}/${item.id}.png`;
  if (item.game === 'hk4e') {
    const key = genshinIcons[item.id];
    return key ? `${ENKA}/ui/${weapon ? 'UI_EquipIcon_' : 'UI_AvatarIcon_Side_'}${key}.png` : null;
  }
  const key = item.game === 'nap' ? zenlessIcons[item.id] : undefined;
  return key ? `${ENKA}/ui/zzz/${key}.png` : null;
}
